export function getFrontendLanguage(): Language {
  const lang = (window as any)?.frappe?.boot?.lang;
  return lang === 'fr' || lang === 'ar' ? lang : 'en';
}

export function translateText(value: string, language = getFrontendLanguage()): string {
  return language === 'en' ? value : translations[language][value] || value;
}

function translateNode(node: Node, language: Language): void {
  if (node.nodeType === Node.TEXT_NODE) {
    const text = node.textContent || '';
    const trimmed = text.trim();
    if (trimmed && translations[language][trimmed]) {
      node.textContent = text.replace(trimmed, translations[language][trimmed]);
    } else if (trimmed) {
      const phrases = Object.keys(translations[language]).sort((a, b) => b.length - a.length);
      let translated = text;
      for (const phrase of phrases) {
        if (translated.includes(phrase)) translated = translated.replaceAll(phrase, translations[language][phrase]);
      }
      if (translated !== text) node.textContent = translated;
    }
    return;
  }
  if (node.nodeType !== Node.ELEMENT_NODE) return;
  const element = node as HTMLElement;
  for (const attribute of ['placeholder', 'title', 'aria-label']) {
    const value = element.getAttribute(attribute);
    if (value && translations[language][value]) element.setAttribute(attribute, translations[language][value]);
  }
  node.childNodes.forEach((child) => translateNode(child, language));
}

export function initFrontendI18n(): void {
  const language = getFrontendLanguage();
  document.documentElement.lang = language;
  document.documentElement.dir = language === 'ar' ? 'rtl' : 'ltr';
  if (language === 'en') return;
  const translate = () => translateNode(document.body, language);
  translate();
  new MutationObserver(translate).observe(document.body, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: ['placeholder', 'title', 'aria-label'] });
}
